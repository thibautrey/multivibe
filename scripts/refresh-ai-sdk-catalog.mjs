import { writeFile } from "node:fs/promises";

// This command updates metadata only. Endpoints and adapter packages are defined in providers.ts.
const providers = ["anthropic", "google", "openrouter", "deepseek", "groq", "togetherai", "cerebras", "perplexity"];
const response = await fetch("https://models.dev/api.json", { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`models.dev failed ${response.status}`);
const text = await response.text();
if (text.length > 20_000_000) throw new Error("models.dev catalog exceeds size limit");
const raw = JSON.parse(text);
const models = {};
for (const provider of providers) {
  if (!raw[provider]?.models) throw new Error(`models.dev is missing ${provider}`);
  models[provider] = Object.values(raw[provider].models)
    .filter((model) => model.status !== "deprecated" && model.modalities?.output?.includes("text") &&
      typeof model.id === "string" && /^[a-zA-Z0-9][a-zA-Z0-9._:/-]{0,199}$/.test(model.id))
    .map((model) => ({
      id: model.id, name: String(model.name ?? model.id).slice(0,200),
      context: Number(model.limit?.context) || undefined, output: Number(model.limit?.output) || undefined,
      tools: model.tool_call === true, reasoning: model.reasoning === true,
      input: model.modalities.input.filter((value) => typeof value === "string"),
      cost: model.cost && Object.fromEntries(Object.entries(model.cost).filter(([,value]) => typeof value === "number" && value >= 0)),
    })).sort((a,b) => a.id.localeCompare(b.id));
  if (!models[provider].length || models[provider].length > 5000) throw new Error(`Invalid ${provider} catalog size`);
}
const catalog = { source: "https://models.dev/api.json", fetchedAt: new Date().toISOString(), models };
await writeFile(new URL("../src/ai-sdk/catalog.generated.ts", import.meta.url),
  `// Generated by npm run catalog:sdk:refresh. Do not edit manually.\nimport type { SdkCatalog } from "./catalog.js";\nexport const SDK_CATALOG: SdkCatalog = ${JSON.stringify(catalog, null, 2)};\n`);
console.log(`Updated metadata for ${Object.values(models).reduce((sum, list) => sum + list.length, 0)} text-generation models.`);
